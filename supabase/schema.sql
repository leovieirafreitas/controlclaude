-- v2: data de nascimento e integração com Mercado Pago
alter table public.subscribers add column if not exists birth_date date;
alter table public.payments    add column if not exists mp_payment_id text;
create unique index if not exists idx_payments_mp on public.payments(mp_payment_id) where mp_payment_id is not null;

create table if not exists public.checkouts (
  id                 bigint generated by default as identity primary key,
  subscriber_id      bigint not null references public.subscribers(id) on delete cascade,
  ref_month          text   not null,
  external_reference text   not null,
  preference_id      text   not null,
  amount_cents       integer not null,
  created_at         timestamptz not null default now()
);
create index if not exists idx_checkouts_sub on public.checkouts(subscriber_id);
alter table public.checkouts enable row level security;
drop policy if exists "checkouts: admin gerencia" on public.checkouts;
create policy "checkouts: admin gerencia" on public.checkouts for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- v3: conta do cliente (login com e-mail e senha). A assinatura continua em subscribers.
create table if not exists public.customers (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  phone         text not null default '',
  birth_date    date not null,
  password_hash text not null,           -- scrypt com salt; nunca a senha em texto
  created_at    timestamptz not null default now()
);
alter table public.subscribers add column if not exists customer_id bigint references public.customers(id);
create index if not exists idx_subscribers_customer on public.subscribers(customer_id);
alter table public.customers enable row level security;
drop policy if exists "customers: admin gerencia" on public.customers;
create policy "customers: admin gerencia" on public.customers for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
-- O cadastro público agora passa pelo servidor (conta + senha), então o insert direto de visitantes sai.
drop policy if exists "subscribers: cadastro pela página de vendas" on public.subscribers;
revoke insert on public.subscribers from anon;

-- v4: códigos de acesso por e-mail (login do admin e "esqueci minha senha")
create table if not exists public.login_codes (
  id         bigint generated by default as identity primary key,
  scope      text    not null default 'admin',   -- admin | reset | login (2ª etapa do login do cliente)
  email      text    not null,
  code_hash  text    not null,                    -- HMAC do código; nunca o código
  expires_at bigint  not null,                    -- epoch em ms
  attempts   integer not null default 0,
  used       boolean not null default false,
  created_at bigint  not null                     -- epoch em ms
);
create index if not exists idx_login_codes_email on public.login_codes(scope, email);
alter table public.login_codes enable row level security;  -- sem políticas: só o servidor acessa

-- v5: controle dos avisos automáticos no WhatsApp (evita mandar a mesma mensagem duas vezes)
create table if not exists public.notifications_sent (
  kind          text   not null,   -- lembrete | atraso_cliente | atraso_admin
  subscriber_id bigint not null references public.subscribers(id) on delete cascade,
  ref           text   not null,   -- mês de referência AAAA-MM
  created_at    timestamptz not null default now(),
  primary key (kind, subscriber_id, ref)
);
alter table public.notifications_sent enable row level security;  -- sem políticas: só o servidor acessa

-- v6: aceite dos Termos de uso e da Política de privacidade no cadastro (prova do consentimento)
alter table public.customers add column if not exists terms_accepted_at timestamptz;
alter table public.customers add column if not exists terms_version text;

-- v7: cancelamento agendado (cliente usa até o fim do período pago) e resposta à pergunta de retenção
alter table public.subscribers add column if not exists cancel_at date;               -- último dia de acesso
alter table public.subscribers add column if not exists cancel_requested_at timestamptz;
alter table public.subscribers add column if not exists retention_answer text;        -- sim | nao (resposta no WhatsApp)

-- v8: confirmação do e-mail no cadastro (a conta só vale depois do código enviado ao e-mail)
alter table public.customers add column if not exists email_verified_at timestamptz;
update public.customers set email_verified_at = coalesce(email_verified_at, created_at, now()) where email_verified_at is null;

-- v9: limite de licenças por plano. Vazio (null) = sem limite.
-- Contam como licença usada as assinaturas "ativo" e "pausado". Atingido o limite, o plano aparece como esgotado.
alter table public.plans add column if not exists max_licenses integer check (max_licenses is null or max_licenses > 0);

-- v9: renovação automática no cartão (assinatura do Mercado Pago / preapproval)
alter table public.subscribers add column if not exists mp_preapproval_id text;   -- id da assinatura no Mercado Pago
alter table public.subscribers add column if not exists autopay_status   text;   -- authorized | paused | cancelled
alter table public.subscribers add column if not exists card_last4       text;   -- final do cartão (para mostrar)
alter table public.subscribers add column if not exists card_brand       text;
alter table public.subscribers add column if not exists next_charge_date date;   -- próxima cobrança automática
create unique index if not exists idx_subscribers_preapproval on public.subscribers(mp_preapproval_id) where mp_preapproval_id is not null;

-- v10: renovação automática recusada → por 7 dias o site vai direto para o pagamento avulso (evita repetir recusas no antifraude)
alter table public.subscribers add column if not exists autopay_failed_at timestamptz;
