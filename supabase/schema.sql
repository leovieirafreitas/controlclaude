-- Esquema do Controle de Assinaturas para Supabase (Postgres)
-- Mesmas tabelas do SQLite local: plans, subscribers, payments, settings.
-- RLS ligado e sem políticas: o acesso público (chave anon) fica bloqueado;
-- o servidor deve usar a chave service_role (ou a conexão Postgres direta).

create table if not exists public.plans (
  id          bigint generated by default as identity primary key,
  name        text    not null,
  price_cents integer not null check (price_cents >= 0),
  description text    not null default '',
  active      boolean not null default true,
  features    text    not null default '',   -- benefícios, um por linha
  featured    boolean not null default false  -- destaque "Recomendado" na página de vendas
);

create table if not exists public.subscribers (
  id         bigint generated by default as identity primary key,
  name       text    not null,
  email      text    not null default '',
  phone      text    not null default '',
  plan_id    bigint  not null references public.plans(id) on delete restrict,
  start_date date    not null default current_date,
  due_day    integer not null default 10 check (due_day between 1 and 28),
  status     text    not null default 'ativo'
             check (status in ('aguardando', 'ativo', 'pausado', 'cancelado')),
  notes      text    not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id            bigint generated by default as identity primary key,
  subscriber_id bigint  not null references public.subscribers(id) on delete cascade,
  ref_month     text    not null check (ref_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),  -- AAAA-MM
  amount_cents  integer not null check (amount_cents >= 0),
  paid_at       date    not null default current_date,
  method        text    not null default 'pix',
  notes         text    not null default '',
  created_at    timestamptz not null default now()
);

create table if not exists public.settings (
  key   text primary key,
  value text not null default ''
);

create index if not exists idx_subscribers_plan   on public.subscribers(plan_id);
create index if not exists idx_subscribers_status on public.subscribers(status);
create index if not exists idx_payments_month     on public.payments(ref_month);
create index if not exists idx_payments_sub       on public.payments(subscriber_id);

alter table public.plans       enable row level security;
alter table public.subscribers enable row level security;
alter table public.payments    enable row level security;
alter table public.settings    enable row level security;

